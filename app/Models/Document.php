<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Casts\Attribute;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\MorphMany;

class Document extends Model
{
    use HasFactory;

    protected $fillable = [
        'type',
        'number',
        'contact_id',
        'location_id',
        'user_id',
        'status',
        'source_document_id',
        'subtotal',
        'tax_total',
        'discount_type',
        'discount_value',
        'total',
        'amount_paid',
        'currency',
        'notes',
        'confirmed_at',
    ];

    protected $appends = [
        'formatted_created_at',
        'formatted_confirmed_at',
    ];

    protected function casts(): array
    {
        return [
            'subtotal' => 'decimal:2',
            'tax_total' => 'decimal:2',
            'discount_value' => 'decimal:2',
            'total' => 'decimal:2',
            'amount_paid' => 'decimal:2',
            'confirmed_at' => 'datetime',
            'created_at' => 'datetime',
            'updated_at' => 'datetime',
        ];
    }

    /**
     * Human-readable date/time for display (e.g. "Jul 9, 2026, 4:59 AM").
     * Keeps the raw created_at column untouched for sorting/filtering —
     * this is purely an additional read-only field sent to the frontend
     * so Vue components don't need to format the raw ISO timestamp
     * themselves in a dozen different places.
     */
    protected function formattedCreatedAt(): Attribute
    {
        return Attribute::get(fn () => $this->created_at?->format('M j, Y, g:i A'));
    }

    protected function formattedConfirmedAt(): Attribute
    {
        return Attribute::get(fn () => $this->confirmed_at?->format('M j, Y, g:i A'));
    }

    public function contact(): BelongsTo
    {
        return $this->belongsTo(Contact::class);
    }

    public function location(): BelongsTo
    {
        return $this->belongsTo(Location::class);
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function sourceDocument(): BelongsTo
    {
        return $this->belongsTo(Document::class, 'source_document_id');
    }

    public function lines(): HasMany
    {
        return $this->hasMany(DocumentLine::class);
    }

    public function payments(): HasMany
    {
        return $this->hasMany(Payment::class);
    }

    /**
     * Stock movements generated by this document (e.g. `sale` movements
     * written at checkout), via the polymorphic reference on stock_movements.
     */
    public function stockMovements(): MorphMany
    {
        return $this->morphMany(StockMovement::class, 'reference');
    }

    /**
     * Recalculates subtotal, tax_total, and total from the current set of
     * lines plus any order-level discount, and persists them. Called after
     * any line is added, updated, removed, or the order-level discount
     * changes — the document's totals are always derived, never hand-set.
     *
     * IMPORTANT: subtotal must be the pre-tax net amount. DocumentLine's
     * `line_total` is already tax-INCLUSIVE (netBeforeTax + taxAmount), so
     * summing line_total directly here would double-count tax once as
     * part of "subtotal" and again as "tax_total" when added together.
     * We back out the pre-tax amount as line_total - tax_amount instead.
     */
    public function recalculateTotals(): void
    {
        $this->loadMissing('lines');

        $subtotal = (float) $this->lines->sum(
            fn (DocumentLine $line) => (float) $line->line_total - (float) $line->tax_amount
        );
        $taxTotal = (float) $this->lines->sum('tax_amount');

        $discountAmount = 0.0;
        if ($this->discount_type === 'percentage' && $this->discount_value !== null) {
            $discountAmount = round($subtotal * ((float) $this->discount_value / 100), 2);
        } elseif ($this->discount_type === 'fixed' && $this->discount_value !== null) {
            $discountAmount = (float) $this->discount_value;
        }

        $total = max(0, $subtotal + $taxTotal - $discountAmount);

        $this->update([
            'subtotal' => $subtotal,
            'tax_total' => $taxTotal,
            'total' => $total,
        ]);
    }

    /**
     * The remaining balance owed on this document.
     */
    public function balanceDue(): float
    {
        return round((float) $this->total - (float) $this->amount_paid, 2);
    }
}